def _compact_coverage_name(value: str | None) -> str:
    return re.sub(r"[\s()]+", "", value or "")


def normalize_coverage_name(coverage_name: str) -> str:
    """
    담보명 정규화 (alias → 표준명)

    Args:
        coverage_name: 원본 담보명

    Returns:
        표준 담보명 (매칭 안 되면 원본 반환)
    """
    normalized = _compact_coverage_name(coverage_name)

    for standard_name, aliases in COVERAGE_ALIASES.items():
        if normalized == _compact_coverage_name(standard_name):
            return standard_name

        for alias in aliases:
            if normalized == _compact_coverage_name(alias):
                return standard_name

    return coverage_name
